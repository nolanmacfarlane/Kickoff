#!/usr/bin/env python3
"""Regenerates src/ts/icons.ts from Phosphor Icons (MIT). Usage:
   npm i --no-save @phosphor-icons/core && python3 tools/make-icons.py
To add a sport icon, add the sport id and the Phosphor icon name below, then run this again."""
import re, sys
base = 'node_modules/@phosphor-icons/core/assets/regular/'
SPORTS = {'soccer': 'soccer-ball', 'basketball': 'basketball', 'baseball': 'baseball', 'tennis': 'tennis-ball', 'cycling': 'bicycle',
          'running': 'person-simple-run', 'bouldering': 'mountains', 'fencing': 'sword', 'golf': 'golf', 'volleyball': 'volleyball',
          'badminton': 'racquet', 'swimming': 'person-simple-swim', 'hiking': 'person-simple-hike', 'yoga': 'person-simple-tai-chi', 'cricket': 'cricket'}
UI = {'chat': 'chat-circle', 'send': 'paper-plane-tilt', 'search': 'magnifying-glass', 'share': 'share-network', 'list': 'list-bullets'}
def inner(name):
    return re.sub(r'^<svg[^>]*>|</svg>\s*$', '', open(base + name + '.svg').read().strip())
out = '''// Icons from Phosphor Icons (https://phosphoricons.com), MIT licence, "regular" weight.
// Licence text: public/licenses/phosphor-icons-LICENSE.txt. Each value is the inside of a 256x256 SVG.
// Generated by tools/make-icons.py. Bouldering uses the mountain icon (Phosphor has no climbing icon).

export const SPORT_ICONS: Record<string, string> = {
'''
for k, v in SPORTS.items(): out += f"  {k}: '{inner(v)}',\n"
out += '};\n\nexport const UI_ICONS: Record<string, string> = {\n'
for k, v in UI.items(): out += f"  {k}: '{inner(v)}',\n"
open(sys.argv[1] if len(sys.argv) > 1 else 'src/ts/icons.ts', 'w').write(out + '};\n')
print('wrote icons.ts')
